package org.netpilot.service;

import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.List;
import org.netpilot.model.HotspotUser;

/**
 * Writes a RouterOS script that creates the users with {@code /import}.
 *
 * <p>Every value is quoted and escaped, so user input cannot break out into extra commands.
 * Each user is wrapped in {@code :do { } on-error={ }} so an existing username is logged and
 * skipped instead of aborting the whole import.
 */
public class RscExporter {

    private final String comment;

    public RscExporter() {
        this("NetPilot " + LocalDate.now());
    }

    public RscExporter(String comment) {
        this.comment = comment;
    }

    public void export(List<HotspotUser> users, Path file) throws IOException {
        try (BufferedWriter writer = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) {
            writer.write("# Generated by NetPilot - " + users.size() + " hotspot users");
            writer.newLine();
            writer.write("# Upload to the router, then run: /import file-name=" + file.getFileName());
            writer.newLine();
            for (HotspotUser user : users) {
                writer.write(command(user));
                writer.newLine();
            }
            writer.write(":log info " + quote("NetPilot: import of " + users.size() + " users finished"));
            writer.newLine();
        }
    }

    String command(HotspotUser user) {
        StringBuilder add = new StringBuilder("/ip hotspot user add")
                .append(" name=").append(quote(user.username()))
                .append(" password=").append(quote(user.password()))
                .append(" profile=").append(quote(user.profile()))
                .append(" server=").append(quote(user.server()));
        if (!user.limitUptime().isBlank()) {
            add.append(" limit-uptime=").append(quote(user.limitUptime()));
        }
        if (user.limitBytes() > 0) {
            add.append(" limit-bytes-total=").append(user.limitBytes());
        }
        add.append(" comment=").append(quote(comment));

        return ":do { " + add + " } on-error={ :log warning "
                + quote("NetPilot: skipped existing user " + user.username()) + " }";
    }

    /** RouterOS string literal: escape backslash, quote, dollar (variables) and question mark. */
    static String quote(String value) {
        StringBuilder sb = new StringBuilder(value.length() + 2).append('"');
        for (char c : value.toCharArray()) {
            switch (c) {
                case '\\', '"', '$', '?' -> sb.append('\\').append(c);
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                default -> sb.append(c);
            }
        }
        return sb.append('"').toString();
    }
}
